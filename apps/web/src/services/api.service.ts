export function CreateApiClient<T extends {}>(opts: ClientOptions) {
  const client = createFetchClient<T>(opts);

  client.use(apiMiddleware);

  const pathBasedClient = wrapAsPathBasedClient(client);
  return pathBasedClient;
}
