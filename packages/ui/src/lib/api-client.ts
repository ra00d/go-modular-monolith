import createFetchClient, {
  type ClientOptions,
  type Middleware,
  wrapAsPathBasedClient,
} from "openapi-fetch";
import type { paths } from "../types/api-schema"; // generated by openapi-typescript

const apiMiddleware: Middleware = {
  async onRequest({ request, options }) {
    // set "foo" header
    return request;
  },
  // async onResponse({ request, response, options }) {
  //   const { body, ...resOptions } = response;
  //   // change status of response
  //   return new Response(body, { ...resOptions, status: 200 });
  // },
  async onError({ error }) {
    // wrap errors thrown by fetch
    return new Error("Oops, fetch failed", { cause: error });
  },
};
const client = createFetchClient<paths>({
  baseUrl: "http://localhost:8000/api",
});

client.use(apiMiddleware);
export const apiClient = wrapAsPathBasedClient(client);
// register middleware
//
export function CreateApiClient<T extends {}>(opts: ClientOptions) {
  const client = createFetchClient<T>(opts);

  client.use(apiMiddleware);

  const pathBasedClient = wrapAsPathBasedClient(client);
  return pathBasedClient;
}
